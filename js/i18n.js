function pack(index) {
  return Object.fromEntries(Object.entries(STRINGS).map(([key, pair]) => [key, pair[index]]));
}

export const DICT = { ar: pack(0), en: pack(1) };

export function translate(language, key, vars) {
  const lang = language === "en" ? "en" : "ar";
  let text = DICT[lang][key] ?? DICT.ar[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function formatLength(mins, language) {
  if (mins == null || !Number.isFinite(mins)) return "—";
  const sign = mins < 0 ? "−" : "";
  const total = Math.abs(Math.round(mins));
  const hours = Math.floor(total / 60);
  const minutes = total % 60;
  const h = language === "en" ? "h" : "س";
  const m = language === "en" ? "m" : "د";
  if (hours === 0) return `${sign}${minutes} ${m}`;
  if (minutes === 0) return `${sign}${hours} ${h}`;
  return `${sign}${hours} ${h} ${minutes} ${m}`;
}

export function formatClockTime(totalMinutes, language) {
  const parts = timeParts(totalMinutes);
  if (parts.display === "—") return "—";
  const period = parts.period === "م"
    ? (language === "en" ? "PM" : "م")
    : (language === "en" ? "AM" : "ص");
  const extra = parts.extra > 0 ? ` +${parts.extra}` : parts.extra < 0 ? ` ${parts.extra}` : "";
  return `${parts.display} ${period}${extra}`;
}

export function formatDateLine(isoDate, language) {
  const [year, month, day] = String(isoDate).split("-").map(Number);
  const names = language === "en" ? WEEKDAYS_EN : WEEKDAYS_AR;
  const months = language === "en" ? MONTHS_EN : MONTHS_AR;
  const weekday = names[weekdayIndex(isoDate)] || "";
  if (language === "en") return `${weekday}, ${months[month - 1]} ${day}, ${year}`;
  return `${weekday}، ${day} ${months[month - 1]} ${year}`;
}

export function formatMonthTitle(key, language) {
  const [year, month] = String(key).split("-").map(Number);
  const months = language === "en" ? MONTHS_EN : MONTHS_AR;
  return `${months[month - 1]} ${year}`;
}

export function weekdayLabel(isoDate, language) {
  const names = language === "en" ? WEEKDAYS_EN : WEEKDAYS_AR;
  return names[weekdayIndex(isoDate)] || "";
}
